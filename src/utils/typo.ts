// Русская типографика: короткие слова и тире не должны оставаться в конце строки.
// Меняем обычный пробел на неразрывный (U+00A0), текст при этом остаётся тем же.
const NB = ' '
const SHORT =
  '(?:в|к|с|о|у|и|а|я|но|на|по|до|за|из|от|об|во|со|ко|не|ни|то|же|бы|ли|для|при|про|без|над|под|что|как|или|это|мой|моя)'
// слово целиком: перед ним начало строки, пробел или открывающая скобка/кавычка
const glue = new RegExp(`(^|[\\s(«„"])(${SHORT})\\s+`, 'giu')
const dash = /\s+([—–])/gu
const rub = /(\d|млн|млрд|тыс\.)\s+₽/gu
const unit = /(\d)\s+(г\.|гг\.|₽|млн|тыс\.|мин|лет|года|год|ГБ|МБ)/gu

export function typoRu(text: string): string {
  if (!text) return text
  let s = text
  // два прохода: «в и о» подряд склеиваются не за один раз
  s = s.replace(glue, `$1$2${NB}`).replace(glue, `$1$2${NB}`)
  return s.replace(dash, `${NB}$1`).replace(unit, `$1${NB}$2`).replace(rub, `$1${NB}₽`)
}
